// Builds the Testing Center spec from test-set/test-set.csv.
//
//   node scripts/build-test-spec.mjs        (or: npm run build:test-spec)
//
// The CSV uses the names a reader sees in Agentforce Builder. Testing Center
// needs the agent's API names, so the two maps below translate one to the
// other. They were fixed before the first baseline run and must not change
// between the baseline and the after runs.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, isMain, parseCsv } from './lib.mjs';

export const SUBAGENT_API_NAMES = {
  'Order Status': 'order_status',
  Returns: 'returns',
  'Product Help': 'product_help',
  Escalation: 'escalation',
  'Off Topic': 'off_topic',
  'Ambiguous Question': 'ambiguous_question',
};
export const ACTION_API_NAMES = {
  'Get Order Status': 'get_order_status',
  'Create Return Case': 'create_return_case',
  'Answer Questions with Knowledge': 'AnswerQuestionsWithKnowledge',
  Escalate: 'escalate_to_human',
};
export const AGENT = 'Gear_Store_Service_Agent';
export const OUTPUT = join(ROOT, 'test-set/testing-center-spec.yaml');

export function expectedActions(row) {
  return row.expected_action === 'None' ? [] : row.expected_action.split(' + ').map(a => ACTION_API_NAMES[a]);
}

const q = s => JSON.stringify(s); // a JSON string is a valid YAML scalar

export function buildSpec(version = 'v1') {
  const { rows } = parseCsv(readFileSync(join(ROOT, 'test-set/test-set.csv'), 'utf8'));
  const lines = [
    '# GENERATED by scripts/build-test-spec.mjs from test-set/test-set.csv. Do not edit by hand.',
    `name: ${q('Store Agent 30 Questions')}`,
    `description: ${q('The locked 30-question test set. Same questions for the baseline and the after runs.')}`,
    'subjectType: AGENT',
    `subjectName: ${AGENT}`,
    `subjectVersion: ${version}`,
    'testCases:',
  ];
  for (const r of rows) {
    lines.push(`  # ${r.id} (${r.category})`);
    lines.push(`  - utterance: ${q(r.customer_says)}`);
    lines.push(`    expectedTopic: ${SUBAGENT_API_NAMES[r.expected_subagent]}`);
    const acts = expectedActions(r);
    lines.push(acts.length ? `    expectedActions:\n${acts.map(a => `      - ${a}`).join('\n')}` : '    expectedActions: []');
    lines.push(`    expectedOutcome: ${q(r.expected_answer)}`);
  }
  return lines.join('\n') + '\n';
}

if (isMain(import.meta.url)) {
  writeFileSync(OUTPUT, buildSpec(process.argv[2] ?? 'v1'));
  console.log(`Wrote ${OUTPUT.replace(ROOT, '')}`);
}
